"""Write the Rules table of `.opengrep/README.md` from `.opengrep/kea-rules.yaml`.

Each row shows the rule id, the severity, the scope from `paths` and the message. The table sits between the
BEGIN and END markers; the rest of the README is hand-written. With `--check`, the script writes nothing and
fails when the table differs from the ruleset.

A message is Markdown: put code names in backticks. The script refuses `*`, `_`, `<` and `[` outside a code
span, because GitHub would render them as emphasis, HTML or a link. It reads a code span as one backtick on
each side, so it refuses an escaped backtick and a run of two backticks. Limit: it also refuses a code span
after an escaped backslash in the prose (two backslashes, then a backtick), which GitHub renders as code.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

RULES = Path(".opengrep/kea-rules.yaml")
README = Path(".opengrep/README.md")
BEGIN = "<!-- BEGIN generated by scripts/opengrep_readme.py from kea-rules.yaml; do not edit -->"
END = "<!-- END generated -->"
_MARKUP = re.compile(r"[*_<\[]")


class MessageError(ValueError):
    """A rule message that does not render as written."""


def _code(text: str) -> str:
    return f"`{text}`".replace("|", "\\|")


def _cell(rule_id: str, text: str) -> str:
    """Return *text* as one table cell, or raise MessageError for markup outside a code span."""
    parts = text.split("`")
    # A backslash is literal inside a code span, so only an opening backtick can be escaped.
    if "``" in text or any(prose.endswith("\\") for prose in parts[:-1:2]):
        raise MessageError(f"{rule_id}: use single unescaped backticks for a code span.")
    if len(parts) % 2 == 0:
        raise MessageError(f"{rule_id}: the message has an unclosed code span.")
    for prose in parts[::2]:
        if match := _MARKUP.search(prose):
            raise MessageError(f"{rule_id}: put {match.group()!r} in a code span (`...`): {prose.strip()!r}")
    return text.replace("|", "\\|")


def _scope(rule: dict) -> str:
    """Return the files that a rule scans, from its `paths`, without its rule-test fixture."""
    paths = rule.get("paths") or {}
    include = [path for path in paths.get("include", ()) if path != f"{rule['id']}.py"]
    scope = ", ".join(map(_code, include)) if include else "every scanned file"
    if exclude := paths.get("exclude"):
        scope += "; not " + ", ".join(map(_code, exclude))
    return scope


def table(rules: list[dict]) -> str:
    """Return the Markdown table of *rules*, in ruleset order."""
    rows = ["| Rule id | Severity | Scope | Message |", "| --- | --- | --- | --- |"]
    for rule in rules:
        message = rule["message"].strip().replace("\n", " ")
        rows.append(
            f"| {_code(rule['id'])} | {rule['severity'].lower()} | {_scope(rule)} | {_cell(rule['id'], message)} |"
        )
    return "\n".join(rows)


def render(readme: str, rules: list[dict]) -> str:
    """Return *readme* with the lines between the marker lines replaced by the table of *rules*."""
    lines = readme.split("\n")
    if lines.count(BEGIN) != 1 or lines.count(END) != 1 or lines.index(BEGIN) > lines.index(END):
        raise MessageError(f"{README} must hold the line {BEGIN!r} and, after it, the line {END!r}, once each.")
    return "\n".join([*lines[: lines.index(BEGIN) + 1], "", table(rules), "", *lines[lines.index(END) :]])


def main(argv: list[str] | None = None) -> int:
    """Write or check the table; return the exit status."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the README table is stale; write nothing")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1], help="repository root")
    args = parser.parse_args(argv)
    readme_path = args.root / README
    rules = yaml.safe_load((args.root / RULES).read_text(encoding="utf-8"))["rules"]
    current = readme_path.read_text(encoding="utf-8")
    try:
        expected = render(current, rules)
    except MessageError as error:
        sys.stderr.write(f"error: {error}\n")
        return 2
    if expected == current:
        return 0
    if args.check:
        sys.stderr.write(f"{README} is stale: run scripts/opengrep_readme.py\n")
        return 1
    readme_path.write_text(expected, encoding="utf-8")
    sys.stderr.write(f"{README}: wrote the Rules table\n")
    return 1


if __name__ == "__main__":
    sys.exit(main())
